package com.apkbuilder;

import java.io.File;
import java.io.IOException;

/**
 * Writes settings.gradle, build.gradle and gradle.properties next to the project's existing
 * src/main/ tree, treating the project root itself as the single Gradle module (its layout -
 * src/main/java, src/main/res, src/main/AndroidManifest.xml - already matches what Gradle's
 * default Android source set expects, so no restructuring is needed).
 *
 * Why this exists: this app's own build pipeline (ECJ + AAPT2 + DX/D8, all on-device, no
 * network) has no way to fetch real Maven artifacts like androidx.appcompat or
 * com.google.android.material - those are several MB each with their own transitive
 * dependencies and need a real network-connected Gradle run to resolve correctly, the same
 * way this very app (ApkBuilder) is itself built. These generated files make every project
 * instantly buildable that way too: open this same project folder as a Gradle project (e.g.
 * in AndroidIDE or Android Studio) and a real "assembleDebug" will fetch and link AppCompat/
 * Material correctly. Regenerated on every ProjectConfig.save(), so it always matches the
 * project's current settings (package name, SDK levels, AppCompat/Material checkboxes...).
 */
public final class GradleFilesGenerator {
    private GradleFilesGenerator() {}

    public static void generate(ProjectConfig cfg) throws IOException {
        Util.writeAtomic(new File(cfg.root, "settings.gradle"), settingsGradle(cfg));
        Util.writeAtomic(new File(cfg.root, "build.gradle"), buildGradle(cfg));
        mergeGradleProperties(cfg);
    }

    private static String settingsGradle(ProjectConfig cfg) {
        return "// Generated by APK Builder. Lets a real Gradle tool (Android Studio, AndroidIDE)\n"
             + "// build this same project with full, network-resolved dependency support.\n"
             + "rootProject.name = '" + escape(cfg.name) + "'\n";
    }

    private static String buildGradle(ProjectConfig cfg) {
        StringBuilder deps = new StringBuilder();
        if (cfg.appCompat) deps.append("    implementation 'androidx.appcompat:appcompat:1.6.1'\n");
        if (cfg.material) deps.append("    implementation 'com.google.android.material:material:1.11.0'\n");
        deps.append("    implementation fileTree(dir: 'libs', include: ['*.jar', '*.aar'])\n");

        int compileSdk = Math.max(34, cfg.targetSdk);

        return "// Generated by APK Builder from this project's settings - edit Settings in the\n"
             + "// app (or the fields below) and keep them in sync; regenerated on every save.\n"
             + "plugins {\n"
             + "    id 'com.android.application'\n"
             + "}\n\n"
             + "android {\n"
             + "    namespace '" + cfg.packageName + "'\n"
             + "    compileSdk " + compileSdk + "\n\n"
             + "    defaultConfig {\n"
             + "        applicationId '" + cfg.packageName + "'\n"
             + "        minSdk " + cfg.minSdk + "\n"
             + "        targetSdk " + cfg.targetSdk + "\n"
             + "        versionCode " + cfg.versionCode + "\n"
             + "        versionName '" + escape(cfg.versionName) + "'\n"
             + "    }\n\n"
             + "    buildTypes {\n"
             + "        release {\n"
             + "            minifyEnabled " + (cfg.r8 || cfg.proguard) + "\n"
             + "            proguardFiles getDefaultProguardFile('proguard-android-optimize.txt'), 'proguard-rules.pro'\n"
             + "        }\n"
             + "    }\n\n"
             + "    compileOptions {\n"
             + "        sourceCompatibility JavaVersion.VERSION_17\n"
             + "        targetCompatibility JavaVersion.VERSION_17\n"
             + "    }\n"
             + "}\n\n"
             + "dependencies {\n"
             + deps
             + "}\n";
    }

    /** AndroidX requires these two flags project-wide. Merges them into any gradle.properties
     *  that already exists (e.g. one AndroidIDE itself created) instead of overwriting it. */
    private static void mergeGradleProperties(ProjectConfig cfg) throws IOException {
        File f = new File(cfg.root, "gradle.properties");
        String existing = f.isFile() ? Util.readText(f) : "";
        StringBuilder out = new StringBuilder(existing);
        if (cfg.appCompat || cfg.material) {
            if (!existing.contains("android.useAndroidX")) out.append("\nandroid.useAndroidX=true\n");
            if (!existing.contains("android.enableJetifier")) out.append("android.enableJetifier=true\n");
        }
        if (!existing.contains("org.gradle.jvmargs")) out.append("org.gradle.jvmargs=-Xmx1536m -Dfile.encoding=UTF-8\n");
        Util.writeAtomic(f, out.toString());
    }

    private static String escape(String s) { return s == null ? "" : s.replace("\\", "\\\\").replace("'", "\\'"); }
}
