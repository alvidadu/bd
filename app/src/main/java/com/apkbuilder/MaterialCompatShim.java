package com.apkbuilder;

import android.content.Context;

import java.io.File;

/**
 * Wires this builder's small, locally-implemented MaterialCardView/TextInputLayout
 * stand-ins (see mini-material-compat.jar, built from com.google.android.material.* sources
 * bundled under assets/libs-material/) into a project whenever AppCompat or Material is
 * checked in Project Settings.
 *
 * This is NOT Google's real AppCompat/Material library - this on-device builder has no
 * network access to fetch it, and correctly merging a real library's own resources (stable
 * IDs shared between its compiled code and the final resource table) is a genuinely complex
 * part of the real Android Gradle Plugin that a naive file copy would get subtly wrong. What
 * this does instead: declare the handful of app:card-* / app:box-* attributes these two widgets
 * actually use in the project's own resources (so AAPT2 can resolve them) and include real,
 * working view classes under the exact real Material class names (so the layout inflates
 * instead of crashing) in both the compile classpath and the final dex.
 */
public final class MaterialCompatShim {
    private MaterialCompatShim() {}

    private static final String ASSET_JAR = "libs-material/mini-material-compat.jar";
    private static final String ATTRS_FILE = "material_compat_attrs.xml";

    /** Writes/refreshes the generated attrs.xml. Safe to call on every build/open - it always
     *  overwrites its own generated file, never anything the user created. */
    public static void ensureAttrs(ProjectConfig cfg) {
        if (!(cfg.appCompat || cfg.material)) return;
        try {
            File dest = new File(cfg.resDir(), "values/" + ATTRS_FILE);
            dest.getParentFile().mkdirs();
            Util.writeAtomic(dest, ATTRS_XML);
        } catch (Exception ignored) {
            // Best-effort: if this fails, the build's own AAPT2 step will surface a clear
            // "attribute not found" error same as before, rather than silently half-working.
        }
    }

    /** Extracts the bundled mini-material-compat.jar (once per app install/update, same
     *  caching approach as BuildManager.bundledLibs()) and returns it, or null if Material/
     *  AppCompat isn't enabled for this project or the asset is missing. */
    public static File extractJarIfNeeded(Context ctx, ProjectConfig cfg) {
        if (!(cfg.appCompat || cfg.material)) return null;
        try {
            File dest = new File(ctx.getFilesDir(), "mini-material-compat.jar");
            Util.copyStreamToFile(ctx.getAssets().open(ASSET_JAR), dest);
            return dest;
        } catch (Exception e) {
            return null;
        }
    }

    private static final String ATTRS_XML =
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
      + "<!-- Auto-generated by APK Builder because AppCompat/Material is enabled in Project\n"
      + "     Settings. Declares just the custom attributes this builder's own lightweight\n"
      + "     MaterialCardView / TextInputLayout stand-ins understand - this on-device builder\n"
      + "     has no network access to fetch Google's real Material library. Regenerated on\n"
      + "     every build; do not hand-edit. -->\n"
      + "<resources>\n"
      + "    <declare-styleable name=\"MaterialCardView\">\n"
      + "        <attr name=\"cardBackgroundColor\" format=\"color\" />\n"
      + "        <attr name=\"cardCornerRadius\" format=\"dimension\" />\n"
      + "        <attr name=\"cardElevation\" format=\"dimension\" />\n"
      + "        <attr name=\"cardUseCompatPadding\" format=\"boolean\" />\n"
      + "        <attr name=\"contentPadding\" format=\"dimension\" />\n"
      + "    </declare-styleable>\n"
      + "    <declare-styleable name=\"TextInputLayout\">\n"
      + "        <attr name=\"boxBackgroundMode\" format=\"enum\">\n"
      + "            <enum name=\"none\" value=\"0\" />\n"
      + "            <enum name=\"outline\" value=\"1\" />\n"
      + "            <enum name=\"filled\" value=\"2\" />\n"
      + "        </attr>\n"
      + "        <attr name=\"boxCornerRadiusTopStart\" format=\"dimension\" />\n"
      + "        <attr name=\"boxCornerRadiusTopEnd\" format=\"dimension\" />\n"
      + "        <attr name=\"boxCornerRadiusBottomStart\" format=\"dimension\" />\n"
      + "        <attr name=\"boxCornerRadiusBottomEnd\" format=\"dimension\" />\n"
      + "        <attr name=\"boxStrokeColor\" format=\"color\" />\n"
      + "        <attr name=\"boxStrokeWidth\" format=\"dimension\" />\n"
      + "        <attr name=\"hintTextColor\" format=\"color\" />\n"
      + "        <attr name=\"hintEnabled\" format=\"boolean\" />\n"
      + "    </declare-styleable>\n"
      + "</resources>\n";
}
